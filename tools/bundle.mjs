// الجولة 8: يدمج سكربتات المتجر في ملف واحد ak-bundle.js (طلب واحد بدل خمسة).
// الترتيب: المحرك (مضغوط من المصدر) ← catflow ← light ← r7 ← q4compare ← r9 (الجولة 9) ← r10 ← r11 (الجولة 11). كل ملف IIFE فيه حارس
// (window.__AK_…__) فلو انحمّل مرتين ما يشتغل مرتين. ak-q4explain.js يبقى منفصل (قسم 4 في 1 بس).
// التشغيل: node tools/bundle.mjs   (يحتاج esbuild: /opt/npm-tools/node_modules/esbuild أو ESBUILD=…)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(import.meta.url);
const esbuild = req(process.env.ESBUILD || '/opt/npm-tools/node_modules/esbuild');
const parts = ['ak-catflow.js', 'ak-light.js', 'ak-r7.js', 'ak-q4compare.js', 'ak-r9.js', 'ak-r10.js', 'ak-r11.js'];
let out = '/* ALKASSER LOOB — ak-bundle.js (generated by tools/bundle.mjs; edit the source files, not this) */\n';
out += readFileSync(path.join(root, 'alkasser-worlds.js'), 'utf8').replace(/\s*$/, '') + '\n;\n';
for (const f of parts) {
  const src = readFileSync(path.join(root, f), 'utf8');
  const { code } = esbuild.transformSync(src, { minify: true, charset: 'utf8', target: 'es2018', legalComments: 'none' });
  out += `/* ${f} */\n` + code.replace(/\s*$/, '') + '\n;\n';
}
writeFileSync(path.join(root, 'ak-bundle.js'), out);
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log('ak-bundle.js', kb(Buffer.byteLength(out)), 'gzip', kb(gzipSync(out).length));
