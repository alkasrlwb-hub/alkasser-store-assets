// الجولة 8: يدمج سكربتات المتجر في ملف واحد ak-bundle.js (طلب واحد بدل خمسة).
// الترتيب: المحرك (مضغوط من المصدر) ← catflow ← light ← r7 ← q4compare ← r9 (الجولة 9) ← r10 ← r11 (الجولة 11) ← r12 (الجولة 12) ← r13 (الجولة 13: المدونة) ← r14 (الجولة 14: إخفاء نسخ cm) ← r15 ← r16 (الجولة 16: البحث بالعالم والتباين). كل ملف IIFE فيه حارس
// (window.__AK_…__) فلو انحمّل مرتين ما يشتغل مرتين. ak-q4explain.js يبقى منفصل (قسم 4 في 1 بس).
// التشغيل: node tools/bundle.mjs   (يحتاج esbuild: /opt/npm-tools/node_modules/esbuild أو ESBUILD=…)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(import.meta.url);
const esbuild = req(process.env.ESBUILD || '/opt/npm-tools/node_modules/esbuild');
const parts = ['ak-catflow.js', 'ak-light.js', 'ak-r7.js', 'ak-q4compare.js', 'ak-r9.js', 'ak-r10.js', 'ak-r11.js', 'ak-r12.js', 'ak-r13.js', 'ak-r14.js', 'ak-r15.js', 'ak-r16.js'];
// الجولة 15: :has(.ak-worlds--X) كان يعيد حساب تنسيق الصفحة كلها مع كل تعديل (تجمد ثواني على الجوال).
// نحوّله لكلاس على <html> (akw-X) يحطه ak-r15.js. وسلايدرات العوالم اللي فيها قسم البلياردو تجيب 9 زيادة لأن نسخ cm المخفية تاخذ أماكن.
const fix = (code) => code.replace(/:has\(\.ak-worlds--(tables|play|moto)\)/g, '.akw-$1');
let out = '/* ALKASSER LOOB — ak-bundle.js (generated by tools/bundle.mjs; edit the source files, not this) */\n';
let eng = fix(readFileSync(path.join(root, 'alkasser-worlds.js'), 'utf8'));
const LIM = 'n.setAttribute(`limit`,String(o))';
if (eng.split(LIM).length !== 2) throw new Error('engine limit hook not found exactly once');
// طلب المالك 28 نوفمبر: «طاولات الألعاب / الأكثر طلباً» (ak-tables-0-0) = 4 منتجات ثابتة بالترتيب: 4 في 1، بلياردو 8 قدم خشبي أزرق، تنس أزرق وأبيض، فرفيرة سوداء
const TOP4 = '[1821944654,2001169038,1369835354,736397998]';
eng = eng.replace(LIM, 'n.setAttribute(`limit`,String(o+(/993213184/.test(String(i||``))?9:0))),t===`ak-tables-0-0`&&(n.setAttribute(`source`,`selected`),n.setAttribute(`source-value`,`' + TOP4 + '`),n.setAttribute(`limit`,`4`))');
if (/:has\(\.ak-worlds--/.test(eng)) throw new Error('engine :has left');
// الجولة 15: قص عناوين البطاقات صار في ak-catflow.js بس (بدون قياس الصفحة كلها مع كل كلمة)، فنوقف نسخة المحرك المكررة (tail-fit، الحارس __AK_TFIT__)
out += 'window.__AK_TFIT__=1;\n';
out += eng.replace(/\s*$/, '') + '\n;\n';
for (const f of parts) {
  const src = readFileSync(path.join(root, f), 'utf8');
  const { code } = esbuild.transformSync(src, { minify: true, charset: 'utf8', target: 'es2018', legalComments: 'none' });
  out += `/* ${f} */\n` + fix(code).replace(/\s*$/, '') + '\n;\n';
}
writeFileSync(path.join(root, 'ak-bundle.js'), out);
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log('ak-bundle.js', kb(Buffer.byteLength(out)), 'gzip', kb(gzipSync(out).length));
